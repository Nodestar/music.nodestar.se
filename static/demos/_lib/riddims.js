/* riddims.js — a small MIDI library the demos can offer in a picker, shared by
   the demos on this site. Not a package: a plain script that registers one
   library on the window. Load it before the page's own script:

     <script src="../_lib/riddims.js"></script>

   What is here
   ------------
   Eight foundation reggae riddims in C minor, two bars each, plus the whole
   set chained back to back. Every file has three parts — drums on channel 10,
   an offbeat skank on channel 1, a dub bassline on channel 2 — so a loader
   that splits a file into drums, chords, bass and melody has something with
   one of each to split. Generated by the reggae-riddims-xy package; the `.mid`
   files sit next to this script in `riddims/`.

   The shape a page consumes
   -------------------------
   window.MidiLibraries   an array of libraries; each script that ships one
                          pushes onto it, so a page can build one picker out of
                          however many are loaded.
   library                {id, name, note, key, items}
   item                   {id, name, url, bpm, bars, swing, note, skipAll}
                          `url` is absolute, resolved from this script's own
                          src, so it works from any demo folder and any depth.
                          `swing` is the percentage the riddim wants set on the
                          device — the MIDI itself is written straight.
                          `skipAll` marks an entry a "load everything" action
                          should leave out (the chain, which is the other eight).

   A page loads one with a plain fetch:

     fetch(item.url).then(function(r){ return r.arrayBuffer(); })
                    .then(function(b){ loadBytes(new Uint8Array(b), item.name); });

   Adding a riddim: drop the `.mid` in `riddims/` and add a line to ITEMS.
*/
(function(root){
"use strict";

var BASE = (function(){
  var s = document.currentScript;
  var src = s && s.src ? s.src : "";
  if(!src){                                   /* deferred or injected: find it */
    var all = document.getElementsByTagName("script");
    for(var i = all.length - 1; i >= 0; i--)
      if(/riddims\.js(\?|$)/.test(all[i].src || "")){ src = all[i].src; break; }
  }
  return src.replace(/[^\/]*$/, "") + "riddims/";
})();

var ITEMS = [
  {id:"one-drop", file:"01_one-drop_78bpm.mid", name:"One Drop", bpm:78, bars:2, swing:18,
   note:"kick and cross-stick together on beat 3, nothing on beat 1; bass rests through the first beat"},
  {id:"rockers", file:"02_rockers_74bpm.mid", name:"Rockers", bpm:74, bars:2, swing:10,
   note:"one drop with a kick on every quarter; bass pumps with it, then walks down C-Bb-Ab-G"},
  {id:"steppers", file:"03_steppers_82bpm.mid", name:"Steppers", bpm:82, bars:2, swing:0,
   note:"four to the floor, dead straight, ride bell on the offbeats; long root under it"},
  {id:"flying-cymbal", file:"04_flying-cymbal_80bpm.mid", name:"Flying Cymbal", bpm:80, bars:2, swing:12,
   note:"closed hat on the beat, open hat on the &; flowing bass with a passing tone"},
  {id:"rub-a-dub", file:"05_rub-a-dub_66bpm.mid", name:"Rub-a-Dub", bpm:66, bars:2, swing:22,
   note:"slow one drop, hats on the offbeats only; the widest, airiest bass of the set"},
  {id:"nyabinghi", file:"06_nyabinghi_70bpm.mid", name:"Nyabinghi", bpm:70, bars:2, swing:26,
   note:"hand-drum heartbeat on kit voices, no skank; bass holds root and fifth"},
  {id:"ska-shuffle", file:"07_ska-shuffle_142bpm.mid", name:"Ska Shuffle", bpm:142, bars:2, swing:55,
   note:"snare on 2 and 4, walking bass in quarters; wants a hard triplet shuffle"},
  {id:"dub-2step", file:"08_dub-2step_132bpm.mid", name:"Dub x 2-Step", bpm:132, bars:2, swing:26,
   note:"hybrid, not traditional: a 2-step kit under an untouched offbeat skank"},
  {id:"chain", file:"00_all-riddims_chain.mid", name:"All eight, chained", bpm:78, bars:32, skipAll:true,
   note:"the whole set back to back, four bars each, with a tempo change and a marker per riddim"}
];

var LIB = {
  id:"reggae-riddims",
  name:"Reggae Riddims",
  note:"Eight foundation reggae riddims in C minor - drums, offbeat skank, dub bassline. Two bars each.",
  key:"C minor",
  base:BASE,
  items:ITEMS.map(function(it){
    it.url = BASE + it.file;
    return it;
  })
};

root.MidiLibraries = root.MidiLibraries || [];
root.MidiLibraries.push(LIB);
root.Riddims = LIB;
})(window);
